def tag(kanji_path: str) -> list[dict]:
    with open(kanji_path, encoding='utf-8') as f:
        kanji_list = json.load(f)
    char_to_tags: dict[str, list[str]] = {}
    for tag_name, chars in TAG_RULES.items():
        for c in chars:
            char_to_tags.setdefault(c, []).append(tag_name)
    result = []
    for k in kanji_list:
        character = k.get('character')
        if character is None:
            print(f"Warning: Skipping entry with missing 'character' key: {k}", file=sys.stderr)
            continue
        tags = char_to_tags.get(character, [])
        result.append({'kanji_id': character, 'tags': tags})
    return result

if __name__ == '__main__':
    script_dir = Path(__file__).parent
    kanji_path = str(script_dir / 'data' / 'kanji.json')

    try:
        data = tag(kanji_path)
    except FileNotFoundError:
        print(f"Error: File not found: {kanji_path}", file=sys.stderr)
        sys.exit(1)
    except json.JSONDecodeError as e:
        print(f"Error: Invalid JSON in {kanji_path}: {e}", file=sys.stderr)
        sys.exit(1)

    try:
        with open(script_dir / 'data' / 'kanji_tags.json', 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
    except OSError as e:
        print(f"Error: Failed to write output file: {e}", file=sys.stderr)
        sys.exit(1)

    tagged = sum(1 for d in data if d['tags'])
    untagged = len(data) - tagged
    print(f"Tagged {tagged} / {len(data)} kanji ({untagged} untagged)")
